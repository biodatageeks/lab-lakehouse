-- Wipe course state between test runs (keeps the warehouse, SHOP.OPS and the notebook project).
-- Dropping a schema also drops its stages, pipes, streams, tasks and dynamic tables.
USE ROLE ACCOUNTADMIN;
DROP SCHEMA IF EXISTS SHOP.BRONZE CASCADE;
DROP SCHEMA IF EXISTS SHOP.SILVER CASCADE;
DROP SCHEMA IF EXISTS SHOP.GOLD CASCADE;
DROP DBT PROJECT IF EXISTS SHOP.OPS.DBT_SHOP;
CREATE SCHEMA SHOP.BRONZE;
CREATE SCHEMA SHOP.SILVER;
CREATE SCHEMA SHOP.GOLD;
CREATE STAGE SHOP.BRONZE.LANDING DIRECTORY = (ENABLE = TRUE) ENCRYPTION = (TYPE = 'SNOWFLAKE_SSE');
